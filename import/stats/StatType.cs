namespace Core.Stats;

/// <summary>
/// Defines the type of a stat.
/// </summary>
public enum StatType
{
	/// <summary>
	/// Represents health or hit points of an entity.
	/// </summary>
	Health,

	/// <summary>
	/// Represents the damage output of an entity.
	/// </summary>
	Damage,

	/// <summary>
	/// Represents the movement speed of an entity.
	/// </summary>
	MoveSpeed,
}
